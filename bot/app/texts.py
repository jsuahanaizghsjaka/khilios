# --- Тарифы ---------------------------------------------------------------


def tariffs() -> str:
    lines = ["<b>💳 Тарифы</b>\n"]
    lines.append(
        f"<b>{TRIAL.name}</b> — 0 ₽, {TRIAL.days} дней, "
        f"{TRIAL.devices} устройство\n<i>{TRIAL.note}</i>\n"
    )
    for p in PAID:
        period = "в месяц" if p.days == 30 else "в год"
        lines.append(
            f"<b>{p.name}</b> — {p.price_rub} ₽ {period}, "
            f"{p.devices} устройств\n<i>{p.note}</i>\n"
        )
    lines.append(
        "Оплата картой МИР, через СБП, Telegram Stars или криптовалютой. "
        "Автосписания нет ни при одном способе: продление — только вашей кнопкой. "
        "Если подписка ещё действует, купленный срок прибавится к текущему."
    )
    return "\n".join(lines)


