#!/usr/bin/env bash
#
# khilios — разворачивание Telegram-бота.
#
# Ставится на ПАНЕЛЬНУЮ VPS, рядом с панелью. Отдельная машина боту не нужна:
# трафик он не носит, а к API панели ходит по localhost — то есть API панели
# не приходится открывать наружу вообще.
#
#   cp bot.env.example bot.env && nano bot.env && ./deploy-bot.sh
#
# ПРО LONG POLLING.
# Бот работает опросом, а не вебхуком, и это осознанно. Вебхук требует
# открытого наружу HTTPS-эндпоинта — то есть ещё одной публичной точки на
# машине, где лежит база всех пользователей и ключи. Ради 15-30 клиентов
# такой размен не нужен: опрос ничего не открывает и при этой нагрузке
# неотличим по скорости.
#
# ПРО СВОЙ КОД, А НЕ ГОТОВОГО БОТА.
# Раньше здесь клонировался сторонний бот (Bedolaga, remnawave-shopbot).
# Отказались: весь раздел «Выключить» из docs/bot-checklist.md — это список
# того, что готовые боты делают по умолчанию. Рефералка с дефолтным бонусом
# при замороженной юристом рефералке и автосписание при обещании «автосписания
# нет» — не настройки, а публично нарушенные обещания. Вычищать чужого бота
# и доказывать, что он не спишет деньги сам, дороже, чем написать своего.
# Код бота — в bot/ этого репозитория.

set -euo pipefail

cd "$(dirname "$0")"

log()  { printf '\n\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m [!]\033[0m %s\n' "$*"; }
die()  { printf '\n\033[1;31m[x] %s\033[0m\n' "$*" >&2; exit 1; }

# --------------------------------------------------------------------------
# 0. Конфиг
# --------------------------------------------------------------------------

[[ $EUID -eq 0 ]] || die "Запускать от root."
[[ -f bot.env ]] || die "Нет bot.env. Скопируй bot.env.example и заполни."

# shellcheck disable=SC1091
source ./bot.env

: "${BOT_TOKEN:?BOT_TOKEN не задан — токен от @BotFather}"
: "${PANEL_API_URL:?PANEL_API_URL не задан, обычно http://127.0.0.1:3002}"
: "${PANEL_API_TOKEN:?PANEL_API_TOKEN не задан — создаётся в панели}"
: "${PANEL_INTERNAL_SQUADS:?PANEL_INTERNAL_SQUADS не задан — UUID внутренних групп панели}"
: "${ADMIN_TELEGRAM_ID:?ADMIN_TELEGRAM_ID не задан — ваш Telegram ID}"
: "${CHANNEL_USERNAME:?CHANNEL_USERNAME не задан — канал для гейта, с @}"

BOT_SRC="$(cd .. && cd .. && pwd)/bot"
[[ -d "$BOT_SRC" ]] || die "Нет каталога с кодом бота: $BOT_SRC"

command -v docker >/dev/null 2>&1 || die "Нет Docker. Сначала deploy-panel.sh."

chmod 600 bot.env

# Панель должна быть жива: бот без неё поднимется, но ключей не выдаст,
# и разбираться в этом потом дороже, чем узнать сейчас.
if ! curl -fsS --max-time 5 -o /dev/null \
  -H "Authorization: Bearer $PANEL_API_TOKEN" \
  "$PANEL_API_URL/api/users?size=1" 2>/dev/null; then
  warn "Панель не отвечает на $PANEL_API_URL."
  warn "Бот без неё не выдаст ни одного ключа. Проверь: docker compose ps в /opt/remnawave"
fi

log "Бот: $BOT_SRC | панель: $PANEL_API_URL | канал: $CHANNEL_USERNAME"

# --------------------------------------------------------------------------
# 1. Предупреждения о том, что тихо выключено
# --------------------------------------------------------------------------
# Оба состояния рабочие и оба легко не заметить. Пустой порог отсечки
# обнаруживается по вынесенным за вечер триалам, пустой токен платёжки —
# по нулю выручки при живом боте.

if [[ -z "${TRIAL_MAX_TELEGRAM_ID:-}" ]]; then
  warn "TRIAL_MAX_TELEGRAM_ID пуст — отсечка по возрасту аккаунта ВЫКЛЮЧЕНА."
  warn "Триал можно выносить новыми аккаунтами. Как откалибровать — в bot.env.example."
fi

if [[ -z "${PAYMENT_TOKEN:-}" ]]; then
  warn "PAYMENT_TOKEN пуст — оплата выключена, бот выдаёт только триалы."
  warn "Это нормально, пока платёжка на модерации."
fi

# --------------------------------------------------------------------------
# 2. Сборка и запуск
# --------------------------------------------------------------------------

cd "$BOT_SRC"

log "Сборка образа"
docker compose build

log "Запуск"
docker compose up -d

# --------------------------------------------------------------------------
# 3. Проверка
# --------------------------------------------------------------------------

log "Проверка"
sleep 6
docker compose ps

# Проверяем, что токен вообще рабочий, до того как ждать сообщений в чате.
BOT_INFO=$(curl -fsS --max-time 10 "https://api.telegram.org/bot$BOT_TOKEN/getMe" 2>/dev/null || echo "")
if echo "$BOT_INFO" | grep -q '"ok":true'; then
  BOT_NAME=$(echo "$BOT_INFO" | sed -n 's/.*"username":"\([^"]*\)".*/\1/p')
  echo "  [ok] токен рабочий, бот @$BOT_NAME"
else
  warn "Telegram не принял токен. Проверь BOT_TOKEN у @BotFather."
fi

# Вебхук и опрос несовместимы: если у бота остался вебхук от прошлых
# экспериментов, опрос не получит ни одного сообщения, и выглядеть это
# будет как «бот молчит без ошибок» — худший вид поломки.
WH=$(curl -fsS --max-time 10 "https://api.telegram.org/bot$BOT_TOKEN/getWebhookInfo" 2>/dev/null || echo "")
WH_URL=$(echo "$WH" | sed -n 's/.*"url":"\([^"]*\)".*/\1/p')
if [[ -n "$WH_URL" ]]; then
  warn "У бота установлен вебхук: $WH_URL"
  warn "При работе опросом он должен быть снят, иначе бот молча не получит ничего:"
  warn "  curl -s 'https://api.telegram.org/bot\$BOT_TOKEN/deleteWebhook'"
else
  echo "  [ok] вебхук не установлен, опрос будет работать"
fi

# Бот обязан быть админом канала — иначе Telegram не даст проверить подписку.
# По правилу «сломанная проверка пускает» это не уронит бота, но гейт
# перестанет работать молча, и вы узнаете об этом по отсутствию подписчиков.
CH=$(curl -fsS --max-time 10 \
  "https://api.telegram.org/bot$BOT_TOKEN/getChatAdministrators?chat_id=$CHANNEL_USERNAME" \
  2>/dev/null || echo "")
if echo "$CH" | grep -q '"ok":true'; then
  echo "  [ok] бот видит администраторов $CHANNEL_USERNAME, гейт будет работать"
else
  warn "Бот не может прочитать администраторов $CHANNEL_USERNAME."
  warn "Сделай его администратором канала (достаточно прав на просмотр участников),"
  warn "иначе гейт по подписке отключится молча и триал получат все подряд."
fi

cat <<EOF

--------------------------------------------------------------------
 Бот запущен из $BOT_SRC

 Проверить руками, по порядку:
   1. /start в боте -> экран согласия -> меню
   2. «Попробовать 7 дней» без подписки на канал -> экран гейта
   3. подписаться, «Я подписался» -> ключ выдан
   4. «Попробовать 7 дней» второй раз -> «пробный уже был»
   5. /health от вашего аккаунта -> панель отвечает

 Полный список приёмки — в docs/bot-checklist.md. Там же то, что легко
 забыть и дорого вспомнить:
   - рефералки в этом боте нет вообще, до ответа юриста
   - автопродления нет, сайт это обещает
   - HWID-лимит включается В ПАНЕЛИ, не в боте

 ВАЖНО: добавь бота в бэкап. База лежит в docker-томе bot-data и в дамп
 панели не попадает — при потере VPS уедут подписки и история оплат.
 См. BOT_DIR и BOT_DB_CONTAINER в infra/panel/backup.sh

 Логи:       cd $BOT_SRC && docker compose logs -f
 Перезапуск: cd $BOT_SRC && docker compose restart
--------------------------------------------------------------------
EOF
