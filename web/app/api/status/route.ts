// Состояние узлов для браузера: страница опрашивает этот маршрут и
// обновляет таблицу без перезагрузки.
//
// Зачем прокси, а не запрос к панели прямо из браузера:
//   1. STATUS_URL остаётся на сервере. Адрес панели — не то, что стоит
//      раздавать всем открывшим страницу;
//   2. не нужен CORS на панели;
//   3. если панель не ответила, мы отдаём честный null, а не оставляем
//      страницу с ошибкой в консоли и старыми данными на экране.

import { getStatus } from "@/lib/status";

export const dynamic = "force-dynamic";

export async function GET() {
  const doc = await getStatus({ fresh: true });

  return Response.json(doc, {
    // no-store здесь обязателен: иначе CDN Vercel закэширует ответ и
    // страница будет «обновляться» одним и тем же снимком.
    headers: { "Cache-Control": "no-store" },
  });
}
