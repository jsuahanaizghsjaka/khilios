// Пара кнопок повторяется в первом экране и в финальном блоке.
// Пока бот не заведён, единственное живое действие на странице — соседняя
// ссылка, и заливку получает она: две одинаковые контурные «таблетки» рядом
// читаются как одна сломанная кнопка, а не как выбор из двух.
function CtaRow({
  secondaryHref,
  secondaryLabel,
}: {
  secondaryHref: string;
  secondaryLabel: string;
}) {
  const live = Boolean(checkoutLink());

  return (
    <div className="btn-row">
      {live ? (
        // Сразу с пробным тарифом в ссылке — кнопка обещает семь дней,
        // значит и открыться должен именно он, а не общее меню.
        <Link className="btn" href={checkoutLink("trial")}>
          Попробовать 7 дней бесплатно
        </Link>
      ) : (
        <span className="btn" aria-disabled="true">
          Скоро открытие
        </span>
      )}
      <Link className={live ? "btn btn--ghost" : "btn"} href={secondaryHref}>
        {secondaryLabel}
      </Link>
    </div>
  );
}

